"""Build the field-limited, offline presentation fixture from recorded run exports.

Run from the website root:
    python3 demo/tools/build_evidence.py --source ../shoepoc

Only the selected records and explicitly allowed fields enter the website. Original
exports, credentials, full commands with scenario markers, and cumulative output do not.
"""
import argparse
import hashlib
import json
from pathlib import Path

RUN = "20261009-203708-example"
SELECTION = [
    ("installer", "1553", "alert:kLtmIqEBo4HuhDyVTp2g", "Authorized software setup", "A"),
    ("discovery", "6cd515ca36a95ac2e7588a9f37a9a1cd", "alert:97tiIqEBo4HuhDyVv5g7", "Attacker directory discovery", "B"),
    ("identity", "1543", "alert:jbtjIqEBo4HuhDyVRJlB", "An employee checks their environment", "C"),
]


def read_rows(path):
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def build(source):
    run_path = source / "data" / "runs" / RUN
    actions = read_rows(run_path / "actions.jsonl")
    logs = read_rows(run_path / "siem_logs.jsonl")
    records = []
    for key, action_ref, log_ref, title, letter in SELECTION:
        action = next(a for a in actions if a["action_ref"] == action_ref)
        log = next(l for l in logs if l["log_ref"] == log_ref)
        assert action["machine"] == log["machine"] == "employee1"
        raw = action["raw"]
        audit = log["raw"]["data"]["audit"]
        command = raw.get("command", action["command"])
        if key == "installer":
            assert "phase=curl-bash" in command
            command = command.split(" && ", 1)[1]  # Exclude the evaluator's syslog marker.
            output = "\n".join(line for line in raw["result"].splitlines() if line.startswith("=> nvm "))
            assert "nvm is already installed" in output
            assert audit["execve"]["a0"] == "curl"
            assert audit["execve"]["a2"] in command
            outcome = "Installer ran; output reports an existing installation being updated. No clean-install success claim."
        elif key == "discovery":
            assert command == "pwd" and raw["status"] == 0
            assert raw["output"]["stdout"] == "/opt"
            assert audit["execve"]["a2"] == command
            output = raw["output"]["stdout"]
            outcome = "Execution confirmed by a completed command result: /opt. No compromise or data theft is established by this command."
        else:
            command = command.split(" && ", 1)[1]
            assert command == "whoami && id && uname -a && hostname"
            assert audit["execve"]["a0"] == "whoami"
            output = raw["result"].splitlines()[0]
            assert output == "employee"
            outcome = "Identity check returned the lab user. The experiment records this as authorized employee activity."
        records.append({
            "id": key, "letter": letter, "title": title,
            "run": RUN, "machine": "employee1",
            "action": {
                "ref": action_ref, "time": action["ts"], "command": command,
                "origin": "employee automation" if action["kind"] == "benign" else "attack simulation",
                "label": action["kind"], "output": output,
                "finished": raw.get("finished_timestamp"), "outcome": outcome,
                "source": f"data/runs/{RUN}/actions.jsonl",
            },
            "log": {
                "ref": log_ref, "time": log["ts"], "rule": log["rule_id"],
                "description": log["description"], "level": log["level"],
                "exe": audit["exe"], "pid": audit["pid"], "ppid": audit["ppid"],
                "arguments": {k: v for k, v in audit["execve"].items() if k == "argc" or k in ("a0", "a1", "a2", "a3")},
                "source": f"data/runs/{RUN}/siem_logs.jsonl",
            },
            "association": "Candidate association supported by host, time and command. These excerpts alone do not prove a unique causal match.",
        })
    # A documented exclusion demonstrates that scheduled attack steps are not all successful.
    unconfirmed = next(a for a in actions if a["action_ref"] == "8490a9561766b0dd8006c28213170e10")
    assert unconfirmed["raw"].get("output") is None
    assert unconfirmed["raw"].get("finished_timestamp") is None
    payload = {
        "run": RUN, "date": "9 October 2026", "timezone": "UTC",
        "counts": {"actions": len(actions), "logs": len(logs), "workstations": 1},
        "records": records,
        "exclusion": {
            "ref": unconfirmed["action_ref"], "command": unconfirmed["command"],
            "reason": "An attack-origin identity check has no output or completion timestamp in this export. It is excluded from executed-activity outcomes.",
        },
        "source_hashes": {name: hashlib.sha256((run_path / name).read_bytes()).hexdigest() for name in ("actions.jsonl", "siem_logs.jsonl")},
    }
    return "// Generated by tools/build_evidence.py. Field-limited recorded excerpts.\nwindow.DEMO_EVIDENCE = " + json.dumps(payload, indent=2, ensure_ascii=False) + ";\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--check", action="store_true", help="Verify the committed fixture without rewriting it")
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / "evidence.js"
    result = build(args.source.resolve())
    if args.check:
        if not target.exists() or target.read_text() != result:
            raise SystemExit("Evidence fixture differs from the selected source records")
        print("Evidence fixture verified against source exports")
    else:
        target.write_text(result)
        print(f"Wrote {target}")
